def main():
    selected = [a.upper() for a in sys.argv[1:]]
    if not ROUTER_BIN.exists() or not MOCK_BIN.exists():
        print("FATAL: test-router or mock-providers binary missing in test-env")
        print("Build them first (see run_test_router.sh)")
        return 2

    cfg_path = build_config()
    # Do NOT unlink the events file — the router holds it open.
    # Unlinking causes writes to go to a deleted inode while the test
    # reads a fresh empty file at the same path.
    # if EVENTS.exists():
    #     EVENTS.unlink()

    mock_proc = subprocess.Popen([str(MOCK_BIN)], cwd=TEST_ROOT,
                                 stdout=subprocess.DEVNULL,
                                 stderr=subprocess.DEVNULL)
    env = os.environ.copy()
    env["CONFIG_FILE"] = str(cfg_path)
    env["MOCK_KEY_1"] = "test-key-1"
    env["MOCK_KEY_2"] = "test-key-2"
    router_proc = subprocess.Popen([str(ROUTER_BIN)], cwd=TEST_ROOT, env=env,
                                   stdout=subprocess.DEVNULL,
                                   stderr=subprocess.DEVNULL)

    try:
        # wait for readiness
        for _ in range(40):
            ok, _ = http_json(f"http://127.0.0.1:{ROUTER_PORT}/health", timeout=2)
            if ok:
                break
            time.sleep(0.5)
        else:
            print("FATAL: router did not become healthy on :%d" % ROUTER_PORT)
            return 2

        print("=" * 78)
        print("NEGATIVE TEST MATRIX — MUST NOT HAPPEN")
        print("=" * 78)
        passed = failed = 0
        for tid, name, fn in TESTS:
            if selected and tid not in selected:
                continue
            try:
                detail = fn()
                print(f"PASS  {tid}  {name}")
                print(f"        {detail}")
                passed += 1
                RESULTS.append((tid, name, "PASS", detail))
            except AssertionError as e:
                print(f"FAIL  {tid}  {name}")
                print(f"        {e}")
                failed += 1
                RESULTS.append((tid, name, "FAIL", str(e)))
            except Exception as e:
                print(f"ERROR {tid}  {name}")
                print(f"        {type(e).__name__}: {e}")
                failed += 1
                RESULTS.append((tid, name, "ERROR", f"{type(e).__name__}: {e}"))
            reset_all_mocks()
            time.sleep(0.4)

        print("=" * 78)
        print(f"NEGATIVE MATRIX: {passed} passed, {failed} failed, "
              f"{passed + failed} total")
        print("=" * 78)

        out = TEST_ROOT / "negative-matrix-results.json"
        out.write_text(json.dumps(
            [{"id": t, "name": n, "status": s, "detail": d}
             for t, n, s, d in RESULTS], indent=2))
        print(f"results written: {out}")
        return 0 if failed == 0 else 1
    finally:
        for p in (router_proc, mock_proc):
            try:
                p.send_signal(signal.SIGTERM)
                p.wait(timeout=5)
            except Exception:
                try:
                    p.kill()
                except Exception:
                    pass


if __name__ == "__main__":
    sys.exit(main())
