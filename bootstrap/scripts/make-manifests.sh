#!/data/data/com.termux/files/usr/bin/bash
# make-manifests.sh — regenerate pinned manifests from the LIVE donor system.
# Run on the current, working device before producing an offline bundle.
# Read-only with respect to the system; writes only into this repo.
set -euo pipefail
. "$(dirname "$0")/../lib/common.sh"

log "Regenerating manifests from live system ..."

dpkg-query -W -f='${binary:Package}\t${Version}\n' | LC_ALL=C sort > "$MANIFESTS/termux-packages.txt"
log "termux-packages.txt: $(wc -l < "$MANIFESTS/termux-packages.txt") packages"

# venv lock — drop editable/local-path lines (handled separately)
"$VENV_DIR/bin/python" -m pip freeze \
  | grep -vE '^-e |^psutil @ file:' \
  > "$MANIFESTS/venv-lock.txt"
log "venv-lock.txt: $(wc -l < "$MANIFESTS/venv-lock.txt") pinned packages"

{
  echo "commit=$(git -C "$AGENT_DIR" rev-parse HEAD)"
  echo "version=$("$VENV_DIR/bin/python" -m pip show hermes-agent | sed -n 's/^Version: //p')"
} > "$MANIFESTS/hermes-pin.txt"
log "pin: $(tr '\n' ' ' < "$MANIFESTS/hermes-pin.txt")"

# config template: sanitize live config (values NEVER written, only shapes/env-names)
"$VENV_DIR/bin/python" - "$MANIFESTS/config.template.yaml" <<'PY'
import os, sys, yaml

OUT = sys.argv[1]
cfg = yaml.safe_load(open(os.path.expanduser("~/.hermes/config.yaml")))

ENV_NAMES = {
    "custom_providers[0].key_env": "HERMES_CUSTOM_API_ZYDIT_IN_API_KEY",
    "custom_providers[1].key_env": "HERMES_CUSTOM_API_ZYDIT_IN_API_KEY",
    "custom_providers[2].key_env": "HERMES_CUSTOM_API_ZYDIT_IN_API_KEY",
    "custom_providers[3].key_env": "HERMES_CUSTOM_API_ZYDIT_IN_API_KEY",
    "custom_providers[4].key_env": "HERMES_CUSTOM_API_INCEPTIONLABS_AI_API_KEY",
    "custom_providers[5].key_env": "HERMES_CUSTOM_API_XKIRO_COM_API_KEY",
    "custom_providers[6].key_env": "HERMES_CUSTOM_LOGFARE_AI_API_KEY",
    "auxiliary.moa_reference.key_env": "HERMES_CUSTOM_API_ZYDIT_IN_API_KEY",
    "auxiliary.vision.fallback_chain[1].key_env": "NVIDIA_API_KEY",
}
BLANK = [
    "model.api_key",
    "mcp_servers.notion.auth",
    "mcp_servers.composio.headers.Authorization",
    "mcp_servers.zernio.headers.Authorization",
    "mcp_servers.twelve-data.auth",
    "mcp_servers.arcade-x.auth",
]

def parse_path(path):
    parts = []
    for tok in path.split("."):
        if "[" in tok:
            head, rest = tok.split("[", 1)
            if head: parts.append(head)
            parts.extend(int(i) for i in rest.rstrip("]").split("]["))
        else:
            parts.append(tok)
    return parts

def walk(node, path=""):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            p = f"{path}.{k}" if path else k
            out[k] = walk(v, p)
        return out
    if isinstance(node, list):
        return [walk(v, f"{path}[{n}]") for n, v in enumerate(node)]
    return node

tmpl = walk(cfg)
def set_path(node, path, value):
    cur = node
    for p in parse_path(path)[:-1]:
        cur = cur[p]
    cur[parse_path(path)[-1]] = value

for p, v in ENV_NAMES.items():
    set_path(tmpl, p, v)
for p in BLANK:
    set_path(tmpl, p, "")
tmpl["_template_notes"] = {
    "secrets": "All secret values are injected at configure time from the secrets bundle; see bootstrap/docs/PROVISIONING.md",
    "generated": "regenerated by make-manifests.sh",
}
with open(OUT, "w") as f:
    yaml.safe_dump(tmpl, f, sort_keys=False)
print(f"config.template.yaml -> {OUT} (structural, no secrets)")
PY

# env template (names only)
grep -vE '^\s*#|^\s*$' "$HERMES_HOME/.env" \
  | cut -d= -f1 | LC_ALL=C sort -u > "$MANIFESTS/env.template"
log "env.template: $(wc -l < "$MANIFESTS/env.template") keys"

log "make-manifests.sh complete — review git diff before committing"
